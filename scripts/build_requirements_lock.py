"""
Build requirements.lock from resolved pins plus PyPI sha256 digests (SEC-14).

Step 1 - resolve (inside the Dockerfile's digest-pinned base image, so the
set matches Linux, constrained to the versions the test suite validated):

    docker run --rm -v "$PWD:/w" -w /w python:3.11-slim@sha256:<digest from Dockerfile> \\
      sh -c "pip install -q pip-tools && pip-compile -q --allow-unsafe --strip-extras \\
             --no-emit-index-url --no-annotate --constraint requirements-constraints.txt \\
             -o /w/.resolved.txt requirements.txt"

Step 2 - add every published distribution's sha256 for each pin:

    python scripts/build_requirements_lock.py .resolved.txt

`pip-compile --generate-hashes` produces the same hashes but downloads every
wheel for every platform to compute them; PyPI's JSON API already publishes
the digests pip verifies against.
"""

from __future__ import annotations

import re
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import httpx

REPO = Path(__file__).resolve().parents[1]
HEADER = """#
# requirements.lock - generated by scripts/build_requirements_lock.py; do not edit.
#
# Pins: pip-compile of requirements.txt inside the Dockerfile's digest-pinned
# python:3.11-slim image, constrained to requirements-constraints.txt (the
# versions the test suite validated). Hashes: every distribution file PyPI
# publishes for each pinned version (sha256). Install with:
#
#   pip install --require-hashes -r requirements.lock
#"""


def read_pins(path: Path) -> list[tuple[str, str, str]]:
    pins = []
    for line in path.read_text(encoding="utf-8").splitlines():
        match = re.match(r"^([A-Za-z0-9_.\-]+)==([^\s;]+)\s*(?:;\s*(.*))?$", line.strip())
        if match:
            pins.append((match.group(1), match.group(2), (match.group(3) or "").strip()))
    return pins


def digests(client: httpx.Client, name: str, version: str) -> list[str]:
    response = client.get(f"https://pypi.org/pypi/{name}/{version}/json")
    response.raise_for_status()
    hashes = sorted({f["digests"]["sha256"] for f in response.json()["urls"] if not f.get("yanked")})
    if not hashes:
        raise RuntimeError(f"PyPI lists no files for {name}=={version}")
    return hashes


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print(__doc__)
        return 2
    pins = read_pins(Path(argv[0]))
    with httpx.Client(timeout=60, follow_redirects=True) as client, ThreadPoolExecutor(8) as pool:
        hashed = list(pool.map(lambda p: (*p, digests(client, p[0], p[1])), pins))

    lines = [HEADER]
    for name, version, marker, hashes in sorted(hashed, key=lambda row: row[0].lower()):
        lines.append(f"{name}=={version}" + (f" ; {marker}" if marker else "") + " \\")
        lines += [f"    --hash=sha256:{h}" + (" \\" if i < len(hashes) - 1 else "") for i, h in enumerate(hashes)]
    (REPO / "requirements.lock").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"requirements.lock: {len(hashed)} packages, {sum(len(r[3]) for r in hashed)} hashes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
