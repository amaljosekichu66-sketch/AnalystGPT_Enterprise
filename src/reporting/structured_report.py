"""
Structured Report.

Canonical business report produced by the Reporting Module.

This object is consumed by the AI Insight Engine,
REST API, Power BI integration, Streamlit frontend,
and future React frontend.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import UTC, datetime
from typing import Any


@dataclass(
    frozen=True,
    slots=True,
)
class StructuredReport:
    """
    Immutable structured business report.

    This is the canonical business document generated by the
    Reporting Module and shared across the application.
    """

    # ==========================================================
    # Report Metadata
    # ==========================================================

    title: str

    executive_summary: str

    # ==========================================================
    # Business Content
    # ==========================================================

    kpis: dict[str, Any]

    analytics: dict[str, Any]

    recommendations: list[str]

    # ==========================================================
    # Metadata
    # ==========================================================

    generated_at: datetime = field(
        default_factory=lambda: datetime.now(
            UTC,
        )
    )

    metadata: dict[str, Any] = field(
        default_factory=dict,
    )

    # ==========================================================
    # Convenience Properties
    # ==========================================================

    # ==========================================================
    # Serialization
    # ==========================================================

    def to_dict(
        self,
    ) -> dict[str, Any]:
        """
        Convert the structured report into a serialisable
        dictionary.
        """

        return {
            "title": self.title,
            "executive_summary": self.executive_summary,
            "kpis": self.kpis,
            "analytics": self.analytics,
            "recommendations": self.recommendations,
            "generated_at": (self.generated_at.isoformat()),
            "metadata": self.metadata,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> StructuredReport:
        """Rebuild a report from `to_dict()` output (used to persist AI job inputs, P2-01)."""
        generated_at = data.get("generated_at")
        return cls(
            title=data.get("title", ""),
            executive_summary=data.get("executive_summary", ""),
            kpis=dict(data.get("kpis") or {}),
            analytics=dict(data.get("analytics") or {}),
            recommendations=list(data.get("recommendations") or []),
            generated_at=datetime.fromisoformat(generated_at) if generated_at else datetime.now(UTC),
            metadata=dict(data.get("metadata") or {}),
        )

    # ==========================================================
    # Representation
    # ==========================================================

    def __repr__(
        self,
    ) -> str:

        return (
            "StructuredReport("
            f"title={self.title!r}, "
            f"kpis={len(self.kpis)}, "
            f"analytics={len(self.analytics)}, "
            f"recommendations={len(self.recommendations)}"
            ")"
        )
